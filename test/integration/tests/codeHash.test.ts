import { describe, it, expect } from 'vitest'
import { createHash } from 'crypto'

import { normalizeRuby, hashRuby } from '../../../src/main/handlers/tests/codeHash'

const lf = [
  'require "spec_helper"',
  '',
  'describe "Login" do',
  '  it "logs in" do',
  "    find(css: '#submit').click",
  '  end',
  'end',
  ''
].join('\n')

describe('hashRuby', () => {
  it('CRLF and indentation do not change the hash', () => {
    const crlfReindented = lf
      .split('\n')
      .map((line) => (line.length ? '      ' + line : line))
      .join('\r\n')
    expect(hashRuby(crlfReindented)).toBe(hashRuby(lf))
  })

  it('blank lines and full-line comments ignored', () => {
    const commented = [
      '# generated by Raider',
      'require "spec_helper"',
      '',
      '   # a note about login',
      'describe "Login" do',
      '',
      '  it "logs in" do',
      "    find(css: '#submit').click",
      '  end',
      'end'
    ].join('\n')
    expect(hashRuby(commented)).toBe(hashRuby(lf))
  })

  it('inline hash in code is kept', () => {
    const submit = lf
    const other = lf.replace("'#submit'", "'#other'")
    expect(hashRuby(submit)).not.toBe(hashRuby(other))
  })

  it('code change flips hash', () => {
    const changed = lf.replace('"logs in"', '"signs in"')
    expect(hashRuby(changed)).not.toBe(hashRuby(lf))
  })
})

describe('normalizeRuby', () => {
  it('trims lines, drops blanks and full-line comments, joins with LF', () => {
    expect(normalizeRuby('  a \r\n\r\n# c\r\n  #x\r\n  b  ')).toBe('a\nb')
  })

  it('keeps # inside code and string interpolation', () => {
    expect(normalizeRuby('x = "#{y}" # trailing')).toBe('x = "#{y}" # trailing')
  })
})

describe('hashRuby output', () => {
  it('is sha256 hex of the normalised text', () => {
    const expected = createHash('sha256').update(normalizeRuby(lf)).digest('hex')
    expect(hashRuby(lf)).toBe(expected)
    expect(hashRuby(lf)).toMatch(/^[0-9a-f]{64}$/)
  })
})
